//! The store listing and the in-app link point at the same page.
//! `docs/privacy.html` is copied onto GitHub Pages; this card is what a
//! reviewer finds without leaving Settings, including while offline. It
//! starts folded to its head, as the Credits card beside it does, and opens
//! when the head is pressed.

/// Public page Play Console should list. Served as a normal HTML document,
/// not a download.
pub const PRIVACY_POLICY_URL: &str = "https://mashu.github.io/dust/privacy/";

use dioxus::prelude::*;

use crate::ui::widgets::{FoldHead, FoldPanel};

/// What Contest mode keeps, said on the card and in the policy alike.
pub const CONTEST_PRIVACY: &str = "In Contest mode, Dust keeps your callsign and the exchange you \
     send (name, state or province, CQ zone, class, section, power) in its settings on this \
     device. Each contest run keeps only your country, continent and CQ zone, so its score can \
     be worked out again. Both are in any backup you save. Dust never sends them anywhere. Clear \
     Your station to remove them. The stations you work are generated by Dust; if one matches a \
     real station, that is chance.";

/// How much of the history is kept, said on the card and in the policy
/// alike: all of it, with no count and no limit but the room a browser
/// gives the site (docs/platforms.md).
pub const HISTORY_KEPT: &str = "Every session is kept until you delete it; a browser keeps them \
     while it gives this site room, and the app says when it has none.";

/// Where Dust runs, which decides where it keeps what it stores, what else
/// keeps a copy, and whom it contacts.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Platform {
    Android,
    Ios,
    Web,
    Linux,
    Windows,
    Mac,
}

impl Platform {
    #[cfg(test)]
    const ALL: [Self; 6] = [
        Self::Android,
        Self::Ios,
        Self::Web,
        Self::Linux,
        Self::Windows,
        Self::Mac,
    ];

    /// The one this build runs on.
    const THIS: Self = if cfg!(target_arch = "wasm32") {
        Self::Web
    } else if cfg!(target_os = "android") {
        Self::Android
    } else if cfg!(target_os = "ios") {
        Self::Ios
    } else if cfg!(target_os = "windows") {
        Self::Windows
    } else if cfg!(target_os = "macos") {
        Self::Mac
    } else {
        Self::Linux
    };

    /// Where what Dust stores is kept, what else copies it, and how it is
    /// deleted, said on the card and in the policy alike. A phone backs
    /// every app up unless told not to, and Dust leaves Android's Auto
    /// Backup on, as it keeps the history through a lost phone; a desktop
    /// uninstaller leaves the user's own folders alone; and a browser keeps
    /// a site's storage by its origin, which Dust shares with every other
    /// GitHub Pages site of the account (docs/platforms.md).
    const fn kept(self) -> &'static str {
        match self {
            Self::Android => {
                "On Android all of this is kept in storage that only the app can read. If backup \
                 is on in Android settings, Android copies it to your Google account, as it does \
                 for most apps, and puts it back on a new phone or when Dust is installed again. \
                 Uninstalling the app deletes it from the phone, but not that copy. Turning backup \
                 off in Android settings stops it."
            }
            Self::Ios => {
                "On an iPhone all of this is kept in storage that only the app can read. iCloud \
                 Backup, and a backup of the iPhone on a computer, copy it as they do for other \
                 apps, and restoring such a backup puts it back. Deleting the app deletes it from \
                 the iPhone, but not those copies."
            }
            Self::Web => {
                "In a browser all of this is kept in the storage of the site mashu.github.io, \
                 which every other site the developer publishes there shares: such a site could \
                 read it or clear it. Clearing the site data for mashu.github.io deletes it, \
                 along with what those sites keep."
            }
            Self::Linux => {
                "On Linux all of this is kept in ~/.local/share/dust. Uninstalling the app leaves \
                 that folder: delete it to delete what Dust stored. A backup of your home folder \
                 copies it."
            }
            Self::Windows => {
                "On Windows all of this is kept in %APPDATA%\\dust. Uninstalling the app leaves \
                 that folder: delete it to delete what Dust stored. A backup of your user folder \
                 copies it."
            }
            Self::Mac => {
                "On a Mac all of this is kept in ~/Library/Application Support/dust. Deleting the \
                 app leaves that folder: delete it to delete what Dust stored. A backup of your \
                 home folder, such as Time Machine makes, copies it."
            }
        }
    }

    /// Who the app contacts: Google for its typefaces, and on the web the
    /// host the app itself is loaded from.
    const fn contacts(self) -> &'static str {
        match self {
            Self::Web => {
                "The web app is served by GitHub Pages, and loads its typefaces from Google \
                 Fonts. Both get your IP address when you open it, as with any site. Your \
                 practice is not part of either. Google and GitHub are the only third parties \
                 the app contacts."
            }
            _ => {
                "The app does load its typefaces from Google Fonts. That request includes your \
                 IP address. Your practice is not part of it. Google is the only third party the \
                 app contacts."
            }
        }
    }
}

#[component]
pub fn PrivacyCard() -> Element {
    let open = use_signal(|| false);
    let kept = Platform::THIS.kept();
    let contacts = Platform::THIS.contacts();
    rsx! {
        div { class: "card stack-sm legal",
            FoldHead { title: "Privacy", note: "No account, no ads, no analytics", open }
            FoldPanel { title: "Privacy", open,
                p { class: "muted",
                    "Dust stores your settings and practice history on this device: speed and alphabet, the groups that were sent, what you typed and how soon after each character's sound you keyed it, with the delay your audio device reports, and the scores. There is no account, and Dust never sends that history anywhere. {HISTORY_KEPT} Any of them can be deleted under Stats → History. While a session runs, when it started is kept too, so that one the app closes under is told of when it next opens."
                }
                p { class: "muted", "{CONTEST_PRIVACY}" }
                p { class: "muted", "{kept}" }
                p { class: "muted", "{contacts}" }
                p { class: "muted",
                    "Dust does not use the microphone, location, or contacts, and it has no ads or analytics."
                }
                p { class: "muted",
                    a {
                        class: "privacy-link",
                        href: PRIVACY_POLICY_URL,
                        target: "_blank",
                        rel: "noopener noreferrer",
                        "Privacy policy"
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testing::Ui;

    /// The card starts folded to its head, and opens onto what Dust keeps,
    /// what Contest mode keeps with it, where this platform keeps it, whom
    /// the app contacts, and the policy.
    #[test]
    fn the_card_starts_folded_and_opens_onto_what_dust_keeps() {
        let mut ui = Ui::new(PrivacyCard, ());
        assert!(
            ui.has("No account, no ads, no analytics"),
            "the head always shows"
        );
        assert!(
            ui.has("<h3 class=\"fold-title\"><button id=\"disclosure-privacy\""),
            "the card is still found among the page's headings: {}",
            ui.html()
        );
        assert!(!ui.has("Privacy policy"), "the body shows on a folded card");
        ui.click("disclosure-privacy");
        assert!(ui.has("aria-expanded=\"true\""));
        for shown in [
            "There is no account",
            HISTORY_KEPT,
            CONTEST_PRIVACY,
            Platform::THIS.kept(),
            Platform::THIS.contacts(),
            PRIVACY_POLICY_URL,
        ] {
            assert!(ui.has(shown), "{shown} is missing from the open card");
        }
        assert!(
            !ui.has("Uninstalling the app deletes what it stored"),
            "no platform deletes everything it stored on an uninstall"
        );
        ui.click("disclosure-privacy");
        assert!(!ui.has(PRIVACY_POLICY_URL), "the head folds the card again");
    }

    /// Each platform says where it keeps what Dust stores, and what else
    /// keeps it: a desktop uninstaller leaves the folder, which the card
    /// names; a phone's own backup keeps a copy past an uninstall; and a
    /// browser keeps it for the whole origin, which other sites share.
    #[test]
    fn each_platform_says_where_its_store_is_and_what_else_keeps_it() {
        for platform in Platform::ALL {
            let kept = platform.kept();
            let says = |words: &str| {
                assert!(kept.contains(words), "{platform:?}: no {words:?} in {kept}");
            };
            match platform {
                Platform::Android => {
                    says("copies it to your Google account");
                    says("when Dust is installed again");
                    says("but not that copy");
                    says("Turning backup off in Android settings stops it");
                }
                Platform::Ios => {
                    says("iCloud Backup");
                    says("but not those copies");
                }
                Platform::Web => {
                    says("the site mashu.github.io");
                    says("every other site the developer publishes there shares");
                    says("along with what those sites keep");
                }
                Platform::Linux => says("~/.local/share/dust"),
                Platform::Windows => says("%APPDATA%\\dust"),
                Platform::Mac => says("~/Library/Application Support/dust"),
            }
            if matches!(
                platform,
                Platform::Linux | Platform::Windows | Platform::Mac
            ) {
                says("leaves that folder");
            }
        }
    }

    /// The web app is loaded from GitHub Pages, so it names GitHub beside
    /// Google; an installed app asks only for its typefaces.
    #[test]
    fn only_the_web_app_names_the_host_it_is_loaded_from() {
        for platform in Platform::ALL {
            let contacts = platform.contacts();
            assert!(contacts.contains("Google Fonts"), "{platform:?}");
            assert_eq!(
                contacts.contains("GitHub Pages"),
                platform == Platform::Web,
                "{platform:?}: {contacts}"
            );
        }
    }

    /// The policy says where each platform keeps what Dust stores, in the
    /// words of each one's card, and names everyone who receives anything:
    /// GitHub, which serves the web app, as well as Google.
    #[test]
    fn the_policy_says_where_each_platform_keeps_its_store() {
        let policy = include_str!("../../docs/privacy.html");
        let flat = policy.split_whitespace().collect::<Vec<_>>().join(" ");
        for platform in Platform::ALL {
            assert!(
                flat.contains(platform.kept()),
                "{platform:?}: the policy does not say {}",
                platform.kept()
            );
        }
        assert!(flat.contains("served by GitHub Pages"));
        assert!(flat.contains("GitHub General Privacy Statement"));
        for gone in [
            "The only data that leaves the device",
            "Nothing is synced between devices or between installs",
            "Google is the only third party the app sends data to",
        ] {
            assert!(!flat.contains(gone), "the policy still says {gone:?}");
        }
    }

    #[test]
    fn the_hosted_policy_is_about_this_app() {
        let policy = include_str!("../../docs/privacy.html");
        assert!(policy.contains("dev.dust.morse"));
        assert!(policy.contains("fonts.googleapis.com"));
        assert!(policy.contains("fonts.gstatic.com"));
        let flat = policy.split_whitespace().collect::<Vec<_>>().join(" ");
        assert!(flat.contains("does not record the microphone"));
        assert!(flat.contains("does not sell personal information"));
        assert!(policy.contains("https://github.com/mashu/dust/issues"));
        // The policy says what Contest mode keeps, as the card does.
        assert!(flat.contains(CONTEST_PRIVACY), "{flat}");
        // The policy says how much of the history is kept, as the card does:
        // all of it, and no count, as the history has none.
        assert!(flat.contains(HISTORY_KEPT), "{flat}");
        for gone in [
            "newest 500",
            "500 sessions",
            "as many of the newest as fit",
            "discarded as you practise",
            "keeps fewer of its newest sessions",
        ] {
            assert!(!flat.contains(gone), "the policy still says {gone:?}");
        }
        // It names where a browser keeps the history, what a deletion
        // leaves, and what an older version's copy of the history is.
        for said in [
            "dust_history",
            "kept for good",
            "small page storage",
            "as it was when you updated",
        ] {
            assert!(flat.contains(said), "the policy does not say {said:?}");
        }
        assert!(
            !policy.to_ascii_lowercase().contains(".pdf"),
            "Play rejects a policy that is a downloadable file"
        );
    }
}
